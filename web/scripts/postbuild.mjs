// After `vite build`: add the M0 audio test at /m0/ and write a service worker that precaches the build.
import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';
const here = path.dirname(new URL(import.meta.url).pathname);
const dist = path.resolve(here, '../dist');
const m0 = path.resolve(here, '../../m0');
execSync(`python3 ${path.join(m0, 'build.py')}`, { stdio: 'inherit' });
fs.cpSync(path.join(m0, 'dist'), path.join(dist, 'm0'), { recursive: true });
fs.writeFileSync(path.join(dist, '.nojekyll'), '');

const files = [];
(function walk(d) { for (const f of fs.readdirSync(d)) { const p = path.join(d, f); if (fs.statSync(p).isDirectory()) walk(p); else files.push(path.relative(dist, p).split(path.sep).join('/')); } })(dist);
const precache = ['./', ...files.filter(f => !f.startsWith('m0/') && f !== '.nojekyll' && f !== 'sw.js').map(f => './' + f)];
const version = Date.now().toString(36);
fs.writeFileSync(path.join(dist, 'sw.js'), `// Generated by postbuild.mjs. Cache-first for the app shell; network-first for catalog JSON.
const CACHE = 'gt-${version}';
const PRECACHE = ${JSON.stringify(precache)};
self.addEventListener('install', e => { e.waitUntil(caches.open(CACHE).then(c => c.addAll(PRECACHE)).then(() => self.skipWaiting())); });
self.addEventListener('activate', e => { e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('fetch', e => {
  const u = new URL(e.request.url);
  if (e.request.method !== 'GET' || u.origin !== location.origin) return;
  if (u.pathname.includes('/catalog/')) {
    e.respondWith(fetch(e.request).then(r => { const c = r.clone(); caches.open(CACHE).then(cc => cc.put(e.request, c)); return r; }).catch(() => caches.match(e.request)));
    return;
  }
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then(hit => hit || fetch(e.request).then(r => { if (r.ok) { const c = r.clone(); caches.open(CACHE).then(cc => cc.put(e.request, c)); } return r; })));
});
`);
console.log(`postbuild: m0 copied, sw.js precaches ${precache.length} files`);
