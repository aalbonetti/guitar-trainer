// After `vite build`: add the M0 audio test at /m0/ and write a service worker that precaches the build.
import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';
const here = path.dirname(new URL(import.meta.url).pathname);
const dist = path.resolve(here, '../dist');
const m0 = path.resolve(here, '../../m0');
execSync(`python3 ${path.join(m0, 'build.py')}`, { stdio: 'inherit' });
fs.cpSync(path.join(m0, 'dist'), path.join(dist, 'm0'), { recursive: true });
fs.writeFileSync(path.join(dist, '.nojekyll'), '');

const files = [];
(function walk(d) { for (const f of fs.readdirSync(d)) { const p = path.join(d, f); if (fs.statSync(p).isDirectory()) walk(p); else files.push(path.relative(dist, p).split(path.sep).join('/')); } })(dist);
const precache = ['./', ...files.filter(f => !f.startsWith('m0/') && f !== '.nojekyll' && f !== 'sw.js').map(f => './' + f)];
const version = Date.now().toString(36);
fs.writeFileSync(path.join(dist, 'sw.js'), `// Generated by postbuild.mjs. Everything (app, catalog, lesson text) comes from one versioned cache, so the
// app never waits on the network and never mixes files from two versions. A new version installs in the
// background and waits; the page shows "Update ready" and activates it with a SKIP_WAITING message.
const PREFIX = 'gt-';
const CACHE = PREFIX + '${version}';
const PRECACHE = ${JSON.stringify(precache)};
self.addEventListener('install', e => { // cache: 'reload' skips the HTTP cache, so a new version never precaches the old version's files.
e.waitUntil(caches.open(CACHE).then(c => c.addAll(PRECACHE.map(u => new Request(u, { cache: 'reload' }))))); });
self.addEventListener('message', e => { if (e.data === 'SKIP_WAITING') self.skipWaiting(); });
self.addEventListener('activate', e => { e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k.startsWith(PREFIX) && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('fetch', e => {
  const u = new URL(e.request.url);
  if (e.request.method !== 'GET' || u.origin !== location.origin || u.pathname.includes('/m0/')) return;
  e.respondWith(caches.open(CACHE).then(c => c.match(e.request, { ignoreSearch: true }).then(hit => hit || fetch(e.request).then(r => { if (r.ok) c.put(e.request, r.clone()); return r; }))));
});
`);
console.log(`postbuild: m0 copied, sw.js precaches ${precache.length} files`);
